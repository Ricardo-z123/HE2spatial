import torch
import os
import numpy as np
import pandas as pd
from PIL import Image, ImageFile
import torchvision.transforms as transforms

ImageFile.LOAD_TRUNCATED_IMAGES = True
Image.MAX_IMAGE_PIXELS = None

# Pre-computed expression matrices are produced by data/hvg_her2st.py once;
# Stage 1/2 datasets now load these instead of recomputing lib-norm+log1p.
PREPROCESSED_EXP_DIR = './data/preprocessed_expression_matrices/her2st'


class HER2STStage1Dataset(torch.utils.data.Dataset):
    """
    Per-slide HER2ST dataset for Stage 1 MLM pretraining.
    Default:
        one sample = one entire slide (variable L = 300-600 spots)
    Optional window mode:
        one sample = one valid local spot-grid window (variable M spots)

    DataLoader uses batch_size=1 in both modes, so variable sequence length is supported.

    Two branches share the same train/eval split logic; they differ only in returned fields:
        branch='spot':  gene expression per spot
        branch='image': H&E patches per spot
    """
    def __init__(
        self,
        train=True,
        fold=0,
        branch='spot',
        use_windows=False,
        window_size=10,
        window_stride=2,
        window_min_spots=80,
    ):
        super().__init__()
        assert branch in ('spot', 'image'), f"branch must be 'spot' or 'image', got {branch}"
        self.train = train
        self.branch = branch
        self.use_windows = use_windows
        self.window_size = int(window_size)
        self.window_stride = int(window_stride)
        self.window_min_spots = int(window_min_spots)

        self.cnt_dir = '/root/autodl-tmp/Her2st/data/ST-cnts'
        self.img_dir = '/root/autodl-tmp/Her2st/data/ST-imgs'
        self.pos_dir = '/root/autodl-tmp/Her2st/data/ST-spotfiles'
        self.r = 224 // 2  # half-side of square H&E patch around each spot center

        gene_list = list(np.load('./data/her_hvg_cut_1000.npy', allow_pickle=True))
        self.gene_list = gene_list

        samples = ['A4', 'A5', 'A6', 'B1', 'B2', 'B3']
        te_names = [samples[fold]]
        tr_names = sorted(set(samples) - set(te_names))  # sorted for deterministic ordering across runs
        self.names = tr_names if train else te_names
        self.id2name = dict(enumerate(self.names))

        print("Loading metadata...")
        self.meta_dict = {i: self.get_meta(i) for i in self.names}
        self.loc_dict = {i: m[['x', 'y']].values.astype(int) for i, m in self.meta_dict.items()}
        self.samples = self.build_samples()
        print(f"Stage 1 sample mode: {'window' if self.use_windows else 'whole-slide'}")
        print(f"Total Stage 1 samples: {len(self.samples)}")

        if branch == 'spot':
            # Load preprocessed expression matrices (already lib-norm + log1p).
            # File generated by data/hvg_her2st.py. Saved shape: [n_genes, n_spots] -> .T -> [n_spots, n_genes]
            self.exp_dict = {}
            for i in self.names:
                npy_path = f"{PREPROCESSED_EXP_DIR}/{i}/preprocessed_matrix.npy"
                if not os.path.exists(npy_path):
                    raise FileNotFoundError(
                        f"Preprocessed expression matrix not found: {npy_path}\n"
                        f"Run 'python data/hvg_her2st.py' first to generate it."
                    )
                self.exp_dict[i] = np.load(npy_path).T   # [785, N] -> [N, 785] to match meta row order
                assert self.exp_dict[i].shape[0] == len(self.meta_dict[i]), \
                    f"Slide {i}: preprocessed_matrix has {self.exp_dict[i].shape[0]} spots " \
                    f"but meta has {len(self.meta_dict[i])}. Re-run hvg_her2st.py."
        else:
            print("Loading imgs ...")
            self.img_dict = {i: self.get_img(i) for i in self.names}
            self.center_dict = {
                i: np.floor(m[['pixel_x', 'pixel_y']].values).astype(int)
                for i, m in self.meta_dict.items()
            }
            if train:
                self.transforms = transforms.Compose([
                    transforms.ColorJitter(0.5, 0.5, 0.5),
                    transforms.RandomHorizontalFlip(),
                    transforms.RandomRotation(degrees=180),
                    transforms.ToTensor(),
                ])
            else:
                self.transforms = transforms.ToTensor()

    def __len__(self):
        """Number of Stage 1 samples: slides in whole-slide mode, windows in window mode."""
        return len(self.samples)

    def __getitem__(self, idx):
        """
        Input (whole-slide mode):
          idx: slide sample index
        Input (window mode):
          idx: valid local window sample index
        Output (branch='spot'):
          gene     [M, 785]   FloatTensor   lib-norm + log1p HVG expression per spot
          coords   [M, 2]     LongTensor    integer global (x, y) grid coords per spot
          slide_id str                       slide name like 'A5'
        Output (branch='image'):
          patches  [M, 3, 224, 224] FloatTensor   H&E 224x224 patches per spot (augmented in train, ToTensor only in eval)
          coords   [M, 2]           LongTensor    integer global (x, y) grid coords per spot
          slide_id str                             slide name
        """
        sample = self.samples[idx]
        name = sample['slide']
        row_indices = sample['row_indices']
        coords = torch.from_numpy(self.loc_dict[name][row_indices]).long()  # integer global (x, y) grid coords per spot

        if self.branch == 'spot':
            gene = torch.from_numpy(self.exp_dict[name][row_indices]).float()
            return {'gene': gene, 'coords': coords, 'slide_id': name}
            # [M, 785] gene expression | [M, 2] grid coords | str slide name

        img = self.img_dict[name]
        centers = self.center_dict[name][row_indices]  # [M, 2] integer pixel centers
        patches = []
        for cx, cy in centers:
            patch = img.crop((cx - self.r, cy - self.r, cx + self.r, cy + self.r))  # crop 224x224 around spot center
            patches.append(self.transforms(patch))
        patches = torch.stack(patches, dim=0)  # stack M per-spot tensors into [M, 3, 224, 224]
        return {'patches': patches, 'coords': coords, 'slide_id': name}
        # [M, 3, 224, 224] H&E patches | [M, 2] grid coords | str slide name

    def build_samples(self):
        """
        Build the Stage 1 sample index.

        Whole-slide mode:
            one sample contains all rows from one slide.
        Window mode:
            one sample contains measured spots inside one valid window on the
            global x/y spot grid. Empty/missing grid positions are ignored; the
            returned sequence contains only real selected spots.
        """
        samples = []
        for name in self.names:
            meta = self.meta_dict[name]
            if not self.use_windows:
                samples.append({
                    'slide': name,
                    'row_indices': np.arange(len(meta), dtype=int),
                    'sample_id': name,
                })
                continue

            slide_samples = self.build_window_samples(name, meta)
            samples.extend(slide_samples)
            print(f"  {name}: {len(slide_samples)} valid windows")
        return samples

    def build_window_samples(self, name, meta):
        """Create valid local window samples for one slide."""
        coords = meta[['x', 'y']].values.astype(int)
        spot_lookup = {
            (int(x), int(y)): row_idx
            for row_idx, (x, y) in enumerate(coords)
        }

        x_min, y_min = coords.min(axis=0)
        x_max, y_max = coords.max(axis=0)

        samples = []
        for x0 in range(x_min, x_max - self.window_size + 2, self.window_stride):
            for y0 in range(y_min, y_max - self.window_size + 2, self.window_stride):
                row_indices = []
                for gx in range(x0, x0 + self.window_size):
                    for gy in range(y0, y0 + self.window_size):
                        row_idx = spot_lookup.get((gx, gy))
                        if row_idx is not None:
                            row_indices.append(row_idx)

                if len(row_indices) < self.window_min_spots:
                    continue

                samples.append({
                    'slide': name,
                    'row_indices': np.array(row_indices, dtype=int),
                    'x0': x0,
                    'y0': y0,
                    'x1': x0 + self.window_size - 1,
                    'y1': y0 + self.window_size - 1,
                    'n_spots': len(row_indices),
                    'sample_id': f"{name}_x{x0}-{x0 + self.window_size - 1}_y{y0}-{y0 + self.window_size - 1}",
                })
        return samples

    def get_meta(self, name):
        """Join HVG counts and spot positions on spot id, mirroring baseline."""
        cnt = self.get_cnt(name)
        pos = self.get_pos(name)
        meta = cnt.join(pos.set_index('id'))
        return meta

    def get_cnt(self, name):
        path = self.cnt_dir + '/' + name + '.tsv'
        df = pd.read_csv(path, sep='\t', index_col=0)
        return df

    def get_pos(self, name):
        path = self.pos_dir + '/' + name + '_selection.tsv'
        # path = self.pos_dir+'/'+name+'_labeled_coordinates.tsv'
        df = pd.read_csv(path, sep='\t')
        x = df['x'].values
        y = df['y'].values
        x = np.around(x).astype(int)
        y = np.around(y).astype(int)
        id = []
        for i in range(len(x)):
            id.append(str(x[i]) + 'x' + str(y[i]))
        df['id'] = id

        return df

    def get_img(self, name):
        pre = self.img_dir + '/' + name[0] + '/' + name # data/her2st/data/ST-imgs/D/D6
        fig_name = os.listdir(pre)[0]
        path = pre + '/' + fig_name
        im = Image.open(path)
        return im
